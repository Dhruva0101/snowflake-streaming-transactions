CREATE WAREHOUSE IF NOT EXISTS XS_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;

CREATE DATABASE IF NOT EXISTS FIN_DEMO;
CREATE SCHEMA IF NOT EXISTS FIN_DEMO.RAW;
CREATE SCHEMA IF NOT EXISTS FIN_DEMO.STAGING;
CREATE SCHEMA IF NOT EXISTS FIN_DEMO.MARTS;

CREATE TABLE IF NOT EXISTS FIN_DEMO.RAW.CARD_TXNS (
  TXN_ID     STRING,
  CARD_ID    STRING,
  MERCHANT   STRING,
  MCC        STRING,
  AMOUNT     NUMBER(12, 2),
  CURRENCY   STRING,
  COUNTRY    STRING,
  TS         TIMESTAMP_TZ,
  IS_FRAUD   BOOLEAN,
  LOADED_AT  TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

